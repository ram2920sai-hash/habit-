"""SQLite for local use; PostgreSQL for Neon/Supabase and ephemeral hosts."""
import re

import psycopg
from psycopg.rows import dict_row


class Row(dict):
    def __getitem__(self,key):
        return list(self.values())[key] if isinstance(key,int) else super().__getitem__(key)


class Result:
    def __init__(self,cursor,lastrowid=None):
        self.cursor=cursor
        self.lastrowid=lastrowid
    def fetchone(self):
        row=self.cursor.fetchone()
        return Row(row) if row is not None else None
    def fetchall(self): return [Row(row) for row in self.cursor.fetchall()]
    def __iter__(self): return iter(self.fetchall())


class Postgres:
    def __init__(self,url):
        # Certificate validation is mandatory for cloud databases. Only local tests
        # may explicitly use sslmode=disable on a loopback-only database.
        from urllib.parse import urlsplit
        host=urlsplit(url).hostname
        options={} if host in ('localhost','127.0.0.1','::1') else {'sslmode':'verify-full','sslrootcert':'system'}
        self.db=psycopg.connect(url,row_factory=dict_row,connect_timeout=20,**options)
    def execute(self,sql,params=()):
        sql=sql.strip()
        if sql.startswith('PRAGMA'):
            return Result(self.db.execute('SELECT 1'))
        if sql=='BEGIN IMMEDIATE':
            # Match SQLite's write serialization across all backend workers.
            return Result(self.db.execute('SELECT pg_advisory_xact_lock(761340208)'))
        sql=sql.replace('?','%s')
        replacements={
            'rate_limits': ' ON CONFLICT (key) DO UPDATE SET started=excluded.started,count=excluded.count',
            'password_resets': ' ON CONFLICT (user_id) DO UPDATE SET code_hash=excluded.code_hash,salt=excluded.salt,expires_at=excluded.expires_at,attempts=excluded.attempts',
            'logs': ' ON CONFLICT (habit_id,log_date) DO UPDATE SET completed=excluded.completed',
        }
        match=re.match(r'INSERT OR REPLACE INTO (\w+)',sql,re.I)
        if match:
            table=match.group(1)
            if table not in replacements: raise ValueError('Unsupported upsert')
            sql=sql.replace('INSERT OR REPLACE','INSERT',1)+replacements[table]
        generated=bool(re.match(r'INSERT INTO (users|habits)\b',sql,re.I))
        cursor=self.db.execute(sql+(' RETURNING id' if generated else ''),params or None)
        return Result(cursor,cursor.fetchone()['id'] if generated else None)
    def executescript(self,script):
        script=re.sub(r'\bid INTEGER PRIMARY KEY', 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',script)
        script=re.sub(r'\bREAL\b','DOUBLE PRECISION',script)
        for statement in script.split(';'):
            if statement.strip(): self.db.execute(statement)
        # No browser Data API access to account tables, including when using Supabase.
        for table in ('users','sessions','habits','logs','password_resets','rate_limits'):
            self.db.execute(f'ALTER TABLE {table} ENABLE ROW LEVEL SECURITY')
            self.db.execute(f'REVOKE ALL ON TABLE {table} FROM PUBLIC')
            for role in ('anon','authenticated'):
                if self.db.execute('SELECT 1 FROM pg_roles WHERE rolname=%s',(role,)).fetchone():
                    self.db.execute(f'REVOKE ALL ON TABLE {table} FROM {role}')
    def commit(self): self.db.commit()
    def rollback(self): self.db.rollback()
    def close(self): self.db.close()
